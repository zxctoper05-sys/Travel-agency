function applyLanguage() {
  const t = I18N[lang];

  document.documentElement.lang = lang;
  document.title = t.metaTitle;

  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute('content', t.metaDescription);

  const ogTitle = document.querySelector('meta[property="og:title"]');
  const ogDescription = document.querySelector('meta[property="og:description"]');

  if (ogTitle) ogTitle.setAttribute('content', t.metaTitle);
  if (ogDescription) ogDescription.setAttribute('content', t.metaDescription);

  navLinks.forEach((link, i) => {
    if (t.nav[i]) link.textContent = t.nav[i];
  });

  const cta = document.querySelector('.head-actions .btn-outline');
  if (cta) cta.textContent = t.navCta;

  const heroTags = document.querySelector('.hero-tags');
  const heroTitle = document.querySelector('.hero h1');
  const heroText = document.querySelector('.hero p');
  const heroButtons = document.querySelectorAll('.hero-ctas .btn');

  setText(heroTags, t.heroTags);
  setText(heroTitle, t.heroTitle);
  setText(heroText, t.heroText);

  if (heroButtons[0]) heroButtons[0].textContent = t.heroBtn1;
  if (heroButtons[1]) heroButtons[1].textContent = t.heroBtn2;

  const about = document.querySelector('#about');
  if (about) {
    setText(about.querySelector('.eyebrow'), t.aboutEyebrow);
    setText(about.querySelector('h2'), t.aboutTitle);

    const ps = about.querySelectorAll('.reveal > p');
    if (ps[0]) setText(ps[0], t.about1);
    if (ps[1]) setText(ps[1], t.about2);
    if (ps[2]) setText(ps[2], t.about3);

    const facts = about.querySelectorAll('.fact');
    facts.forEach((fact, i) => {
      if (!t.facts[i]) return;
      const strong = fact.querySelector('strong');
      const span = fact.querySelector('span');
      setText(strong, t.facts[i][0]);
      setText(span, t.facts[i][1]);
    });
  }

  const certificates = document.querySelector('#certificates');
  if (certificates) {
    setText(certificates.querySelector('.eyebrow'), t.certEyebrow);
    setText(certificates.querySelector('h2'), t.certTitle);
  }

  const routesSection = document.querySelector('#routes');
  if (routesSection) {
    const header = routesSection.querySelector('.container.reveal');
    if (header) {
      setText(header.querySelector('.eyebrow'), t.routesEyebrow);
      setText(header.querySelector('h2'), t.routesTitle);
    }

    // Content keys for each route, in page order: [static block], accordion, accordion...
    const ROUTE_KEYS = [
      ['expect', 'learn', 'optional', 'organization', 'meeting'],
      ['expect', 'extra', 'important'],
      ['expect', 'finish', 'organization'],
      ['expect', 'organization'],
      ['expect', 'organization']
    ];

    routesSection.querySelectorAll('.route').forEach((routeEl, index) => {
      const data = t.routes[index];
      if (!data) return;

      setText(routeEl.querySelector('h3'), data.title);
      setText(routeEl.querySelector('.route-lead'), data.lead);

      routeEl.querySelectorAll('.route-block, .route-accordion').forEach((item, i) => {
        const key = ROUTE_KEYS[index][i];
        if (!key) return;

        if (item.tagName === 'DETAILS') {
          setText(item.querySelector('summary'), data.labels[i]);
          setText(item.querySelector('.acc-body'), data[key]);
        } else {
          setText(item.querySelector('h4'), data.labels[i]);
          setText(item.querySelector('p'), data[key]);
        }
      });

      const warning = routeEl.querySelector('.route-warning');
      if (warning && data.warning) setText(warning, data.warning);

      const source = routeEl.querySelector('.route-source a');
      if (source) source.textContent = t.routeSource;
    });
  }

  const fleet = document.querySelector('#fleet');
  if (fleet) {
    setText(fleet.querySelector('.eyebrow'), t.fleetEyebrow);
    setText(fleet.querySelector('h2'), t.fleetTitle);

    const intro = fleet.querySelector('.fleet-intro');
    setText(intro, t.fleetIntro);

    const cats = fleet.querySelectorAll('.fleet-cat');

    cats.forEach((cat, i) => {
      if (!t.fleet[i]) return;

      setText(cat.querySelector('h3'), t.fleet[i][0]);
      setText(cat.querySelector('.fleet-text'), t.fleet[i][1]);
    });

    const fleetGroups = fleet.querySelectorAll('.fleet-group h4');
    fleetGroups.forEach((el, i) => {
      if (t.fleetNames[i]) el.textContent = t.fleetNames[i];
    });
  }

  const contact = document.querySelector('#contact');

  if (contact) {
    setText(contact.querySelector('.eyebrow'), t.contactEyebrow);
    setText(contact.querySelector('h2'), t.contactTitle);

    const contactText = contact.querySelector('.contact-grid > .reveal > p');
    setText(contactText, t.contactText);

    const labels = contact.querySelectorAll('.form-field label');
    if (labels[0]) labels[0].textContent = t.form[0];
    if (labels[1]) labels[1].textContent = t.form[1];
    if (labels[2]) labels[2].textContent = t.form[2];
    if (labels[3]) labels[3].textContent = t.form[3];

    const submit = contact.querySelector('button[type="submit"]');
    if (submit) submit.textContent = t.form[4];

    const select = contact.querySelector('select[name="route"]');

    if (select) {
      select.querySelectorAll('option').forEach((option, i) => {
        if (t.routes[i]) {
          option.textContent = t.routes[i].title;
        }
      });
    }
  }

  const footer = document.querySelector('footer');

  if (footer) {
    const footerColumns = footer.querySelectorAll('.footer-grid > div');

    if (footerColumns[0]) {
      setText(footerColumns[0].querySelector('p'), t.footerAbout);
    }

    if (footerColumns[1]) {
      setText(footerColumns[1].querySelector('h5'), t.footerNav);

      const navMap = { '#about': 0, '#certificates': 1, '#routes': 2, '#fleet': 3, '#contact': 4 };
      footerColumns[1].querySelectorAll('a').forEach(a => {
        const i = navMap[a.getAttribute('href')];
        if (i !== undefined) a.textContent = t.nav[i];
      });
    }

    if (footerColumns[2]) {
      setText(footerColumns[2].querySelector('h5'), t.footerRoutes);

      const routeLinks = footerColumns[2].querySelectorAll('a');
      routeLinks.forEach((link, i) => {
        if (t.routes[i]) link.textContent = t.routes[i].title;
      });
    }

    if (footerColumns[3]) {
      setText(footerColumns[3].querySelector('h5'), t.footerContact);
    }

    const copy = footer.querySelector('.footer-bottom span');
    if (copy) copy.textContent = t.footerCopy;

    const themeBtn2 = document.getElementById('themeBtn2');
    if (themeBtn2) themeBtn2.textContent = t.theme;
  }

  const langBtn = document.getElementById('langBtn');
  if (langBtn) {
    langBtn.textContent = lang === 'ru' ? 'EN' : 'RU';
    langBtn.setAttribute('aria-label', lang === 'ru' ? 'Switch to English' : 'Переключить на русский');
  }

  const langBtn2 = document.getElementById('langBtn2');
  if (langBtn2) {
    langBtn2.textContent = lang === 'ru' ? 'EN' : 'RU';
  }

  const formMsg = document.getElementById('formMsg');

  if (formMsg && formMsg.classList.contains('err')) {
    formMsg.textContent = t.error;
  }

  if (formMsg && formMsg.classList.contains('info')) {
    formMsg.textContent = t.formInfo;
  }
}

